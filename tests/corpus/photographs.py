def path_for(entry) -> str:
    return os.path.join(DIRECTORY, entry["file"])


def present() -> bool:
    return all(os.path.exists(path_for(entry)) for entry in PHOTOGRAPHS)


def fetch():                             # pragma: no cover - reaches the network
    """
    Download the six photographs from Wikimedia Commons.

    Deliberately not run by anything automatically, and not by the tests. This
    project's promise is that it does not reach the network while doing its job,
    and a test suite that quietly downloads several megabytes would be the first
    crack in that. Somebody runs this on purpose, once.
    """
    import urllib.request

    os.makedirs(DIRECTORY, exist_ok=True)
    for entry in PHOTOGRAPHS:
        target = path_for(entry)
        if os.path.exists(target):
            print(f"  have  {entry['file']}")
            continue
        request = urllib.request.Request(
            entry["url"], headers={"User-Agent": "crossfoot-corpus/0.1"})
        with urllib.request.urlopen(request, timeout=120) as response:
            data = response.read()
        with open(target, "wb") as handle:
            handle.write(data)
        digest = hashlib.sha256(data).hexdigest()[:16]
        print(f"  got   {entry['file']}  {len(data):,} bytes  sha256:{digest}")
        print(f"        {entry['credit']}")


if __name__ == "__main__":               # pragma: no cover - a person runs this
    fetch()
