"""
Six photographs of real paper, and what a person read off them.

Everything else in this corpus is rendered text with damage applied. That was
always the honest limit of it, stated in the README: it is a real test and it is
not paper. These are paper. Somebody held a camera over a till receipt, and the
creases, the dot-matrix ink, the aged thermal stock and the wood table under it
are all really there rather than simulated by a filter.

**The images are not in the repository.** They are freely licensed -- that was
the selection criterion, and the licence and author of each are recorded below
so attribution survives -- but several megabytes of JPEG in a repository whose
entire point is that it has no required dependencies would be a strange trade,
and mirroring somebody's photograph is not necessary when the URL is stable.
`python -m tests.corpus.photographs` fetches them; the tests skip, loudly, when
they are absent.

The truth was keyed by looking at each photograph and writing down the numbers
printed on it. That is the only way it can be done, and it is the reason this
file is worth more than the twenty-two rendered ones: nothing about it was
generated by the same process that is being tested.

Each entry carries what the paper says, and separately the numbers on it that
are *not* the receipt's arithmetic -- the cash tendered, the change, the
currency conversion. Those are the traps, and they are recorded because a
parser that reports the change as the total is wrong in the exact way this
project exists to catch.
"""
